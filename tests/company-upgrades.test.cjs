const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const beforeEvents = source.slice(0, source.indexOf("  document.addEventListener('click'"));
const storage = new Map();
const elements = new Map();
const element = key => {
  if (!elements.has(key)) elements.set(key, { innerHTML: '', textContent: '', hidden: false, close() {} });
  return elements.get(key);
};
const math = Object.create(Math);
math.random = Math.random;
const context = vm.createContext({
  localStorage: { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value) },
  Date, Math: math, Intl, Number, JSON, setTimeout, clearTimeout,
  document: { querySelector: element }
});
vm.runInContext(beforeEvents + '\n globalThis.api = { COMPANY_BALANCE, TRANSPORT_UPGRADE_LIMITS, newGame, loadGame, save, transportRules, transportUpgradeCost, upgradeTransport, upgradeWorkshop, upgradeSales, upgradeOfferLimit, createOrder, orderEconomics, companyItemProgress, makeCompletionReward, applyOrderReward, craftCustomerOrder, assignCraftedOrder, settleTrips, settleExpeditions, renderCompany, renderInventory, renderDevelopment, setGame: value => { game = value; }, mute: () => { render = () => {}; showToast = () => {}; } };\n})();', context);
const api = context.api;
api.mute();

const state = api.newGame('hamburg');
api.setGame(state);
state.company.transportUpgrades.national = { premiumLevel: 100, volumeLevel: 50, rangeLevel: 50 };
state.company.transportUpgrades.international = { premiumLevel: 100, volumeLevel: 150, rangeLevel: 100 };
assert.deepEqual(JSON.parse(JSON.stringify(api.transportRules('national'))), { minDistance: 30, maxDistance: 150, minVolume: 35, maxVolume: 90, premiumPerTon: 1, premiumBonus: 1 });
assert.deepEqual(JSON.parse(JSON.stringify(api.transportRules('international'))), { minDistance: 100, maxDistance: 300, minVolume: 85, maxVolume: 200, premiumPerTon: 1, premiumBonus: 1 });
math.random = () => 0;
assert.equal(api.createOrder(10, { category: 'national' }).volume, 35);
assert.equal(api.createOrder(11, { category: 'international' }).volume, 85);
math.random = () => .999;
assert.equal(api.createOrder(12, { category: 'national' }).volume, 90);
assert.equal(api.createOrder(13, { category: 'international' }).volume, 200);
math.random = Math.random;
assert.equal(api.transportUpgradeCost('national', 'premium'), null);
assert.equal(api.upgradeTransport('national', 'premium'), false, 'maximum level cannot be exceeded');
api.renderCompany();
assert.equal((element('#transport-upgrade-grid').innerHTML.match(/class="offer-upgrade-card"/g) || []).length, 6);
assert.match(element('#transport-upgrade-grid').innerHTML, /35–90 t Auftragsmenge/);
state.company.transportUpgrades.national = { premiumLevel: 0, volumeLevel: 0, rangeLevel: 0 };
state.company.transportUpgrades.international = { premiumLevel: 0, volumeLevel: 0, rangeLevel: 0 };
state.coins = 2000;
assert.equal(api.upgradeTransport('national', 'premium'), false, 'items and coins are both required');
state.inventory.companyItems = 2;
const order = { category: 'national', kind: 'normal', routeType: 'single', volume: 20, distance: 60, customer: null };
const truck = state.trucks[0];
const before = api.orderEconomics(order, truck);
assert.equal(api.upgradeTransport('national', 'premium'), true);
assert.equal(state.inventory.companyItems, 0);
assert.equal(state.coins, 1990);
assert.equal(state.company.transportUpgrades.national.premiumLevel, 1);
const after = api.orderEconomics(order, truck);
assert.equal(after.bonus, before.bonus + .2);
assert.equal(after.revenue, before.revenue, 'ton-kilometer revenue is unchanged');
assert.equal(after.cost, before.cost, 'vehicle and load costs are unchanged');
let totalItems = 0, totalCoins = 0, totalLevels = 0;
for (const limits of Object.values(api.TRANSPORT_UPGRADE_LIMITS)) for (const [kind, maximum] of Object.entries(limits)) for (let level = 1; level <= maximum; level++) {
  totalItems += api.COMPANY_BALANCE.transportUpgradeItems(level);
  totalCoins += api.COMPANY_BALANCE.transportUpgradeCoins(kind, level);
  totalLevels++;
}
assert.deepEqual([totalLevels, totalItems, totalCoins], [550, 3700, 103854500]);
state.company.transportUpgrades.national.premiumLevel = 10;
assert.deepEqual(JSON.parse(JSON.stringify(api.transportUpgradeCost('national', 'premium'))), { items: 3, coins: 1210 });
state.inventory.companyItems = 2;
state.coins = 1210;
assert.equal(api.upgradeTransport('national', 'premium'), false, 'insufficient items debit neither resource');
state.inventory.companyItems = 3;
state.coins = 1209;
assert.equal(api.upgradeTransport('national', 'premium'), false, 'insufficient coins debit neither resource');
state.coins = 1210;
assert.equal(api.upgradeTransport('national', 'premium'), true);
assert.equal(state.company.transportUpgrades.national.premiumLevel, 11);
assert.equal(state.inventory.companyItems, 0);
assert.equal(state.coins, 0);

assert.deepEqual(JSON.parse(JSON.stringify(api.companyItemProgress(order, 749000))), { items: 1, remainder: 200 }, 'rest reaches the shared threshold');
assert.deepEqual(JSON.parse(JSON.stringify(api.companyItemProgress({ ...order, routeType: 'dual' }, 749000))), { items: 1, remainder: 1400 }, 'dual way counts both loaded legs');
assert.deepEqual(JSON.parse(JSON.stringify(api.companyItemProgress({ ...order, crafted: true }, 749000))), { items: 1, remainder: 200 }, 'crafted normal orders also count');
assert.deepEqual(JSON.parse(JSON.stringify(api.companyItemProgress({ ...order, kind: 'special' }, 749000))), { items: 0, remainder: 749000 });
assert.deepEqual(JSON.parse(JSON.stringify(api.companyItemProgress({ ...order, volume: 20, distance: 750000 }, 0))), { items: 20, remainder: 0 }, 'large jobs can cross multiple thresholds');

const completed = { id: 'ITEM-1', status: 'completed', ...order, completionReward: api.makeCompletionReward(order, 1) };
state.orders = [completed];
assert.equal(completed.completionReward.companyItems, 1);
assert.equal(api.applyOrderReward(completed), true);
assert.equal(state.inventory.companyItems, 1);
assert.equal(api.applyOrderReward(completed), false);
api.save();
const reloaded = api.loadGame();
api.setGame(reloaded);
assert.equal(api.applyOrderReward(reloaded.orders[0]), false, 'claim survives reload');
assert.equal(reloaded.inventory.companyItems, 1);
reloaded.inventory.companyItemTkmRemainder = 749000;
const live = api.createOrder(999, { category: 'national', customer: null });
Object.assign(live, { status: 'active', truckId: reloaded.trucks[0].id, volume: 10, distance: 100, delivered: 0, tripCargo: 4, tripStartAt: Date.now() - 3600000, routeType: 'single' });
reloaded.orders.push(live);
api.settleTrips(Date.now());
assert.equal(live.status, 'completed');
assert.equal(live.completionReward.companyItems, 1);
assert.equal(reloaded.inventory.companyItemTkmRemainder, 0);
assert.equal(reloaded.inventory.companyItems, 1, 'earned item waits for reward claim');
assert.equal(api.loadGame().orders.find(item => item.id === live.id).completionReward.companyItems, 1, 'completion and counter survive reload');
assert.equal(api.applyOrderReward(live), true);
assert.equal(reloaded.inventory.companyItems, 2);
assert.equal(api.applyOrderReward(live), false);
api.save();
assert.equal(api.loadGame().inventory.companyItems, 2);

reloaded.inventory.companyItems = api.COMPANY_BALANCE.craftedOrderItems;
assert.equal(api.craftCustomerOrder(), false, 'no unlocked customer means no item spend');
assert.equal(reloaded.inventory.companyItems, api.COMPANY_BALANCE.craftedOrderItems);
api.renderDevelopment();
assert.match(element('#development-content').innerHTML, /data-craft-customer disabled/);
reloaded.expedition.regions[0].customerUnlocked = true;
math.random = () => 0;
assert.equal(api.craftCustomerOrder(), true);
const crafted = reloaded.orders.find(item => item.crafted);
assert.equal(crafted.customer, 'nordbau');
assert.equal(crafted.category, 'national');
assert.equal(crafted.status, 'queued');
assert.equal(reloaded.inventory.companyItems, 0);
assert.equal(api.companyItemProgress({ ...crafted, delivered: crafted.volume }, 749900).items, 1);
assert.equal(api.makeCompletionReward(crafted).companyItems, 0, 'items are determined only at actual completion');
assert.equal(api.craftCustomerOrder(), false, 'a second click cannot spend unavailable items');
assert.equal(api.loadGame().orders.find(item => item.id === crafted.id).status, 'queued');
api.renderInventory();
assert.match(element('#inventory-content').innerHTML, new RegExp(`data-start-crafted="${crafted.id}"`));
assert.equal(api.assignCraftedOrder(crafted.id, reloaded.trucks[0].id), true);
assert.equal(crafted.status, 'active');
assert.equal(api.assignCraftedOrder(crafted.id, reloaded.trucks[0].id), false);
assert.equal(api.loadGame().orders.find(item => item.id === crafted.id).status, 'active');
reloaded.expedition.regions[4].customerUnlocked = true;
reloaded.inventory.companyItems = 10;
math.random = () => .999;
assert.equal(api.craftCustomerOrder(), true);
const distantCustomerOrder = reloaded.orders.filter(item => item.crafted).at(-1);
assert.equal(distantCustomerOrder.customer, 'eurolog', 'all unlocked customers participate uniformly');
assert.equal(distantCustomerOrder.category, 'international', 'customer segment is retained');
assert.equal(distantCustomerOrder.status, 'queued');
assert.equal(reloaded.inventory.companyItems, 0);

const material = { id: 99, region: 0, kind: 'endless', lootKind: 'material', tier: 3, status: 'active', endsAt: 0 };
reloaded.expedition.missions = [material];
const beforeMaterial = reloaded.inventory.companyItems;
math.random = () => .05;
api.settleExpeditions(1);
assert.equal(material.status, 'completed');
assert.equal(material.companyItemsAwarded, 3);
assert.equal(reloaded.inventory.companyItems, beforeMaterial + 3);
api.settleExpeditions(2);
assert.equal(reloaded.inventory.companyItems, beforeMaterial + 3, 'material reward is granted only once');
const afterMaterialReload = api.loadGame();
api.setGame(afterMaterialReload);
api.settleExpeditions(2);
assert.equal(afterMaterialReload.inventory.companyItems, beforeMaterial + 3, 'material award survives reload without duplication');
const materialMiss = { id: 100, region: 0, kind: 'endless', lootKind: 'material', tier: 2, status: 'active', endsAt: 0 };
afterMaterialReload.expedition.missions.push(materialMiss);
math.random = () => .06;
api.settleExpeditions(3);
assert.equal(materialMiss.companyItemsAwarded, 0, '6 % boundary does not award items');
assert.equal(afterMaterialReload.inventory.companyItems, beforeMaterial + 3);
const characterMission = { id: 101, region: 0, kind: 'endless', lootKind: 'character', tier: 3, status: 'active', endsAt: 0 };
afterMaterialReload.expedition.missions.push(characterMission);
math.random = () => 0;
api.settleExpeditions(4);
assert.equal(characterMission.companyItemsAwarded, undefined, 'other expedition types do not produce company items');
assert.equal(afterMaterialReload.inventory.companyItems, beforeMaterial + 3);

const departments = api.newGame('hamburg');
api.setGame(departments);
departments.company.departments = { workshop: true, sales: true, dispatch: true };
departments.coins = 5000;
api.upgradeWorkshop();
assert.equal(departments.company.workshopLevel, 0, 'department upgrade needs an item');
departments.inventory.companyItems = 3;
api.upgradeWorkshop();
api.upgradeSales();
api.upgradeOfferLimit();
assert.equal(departments.company.workshopLevel, 1);
assert.equal(departments.company.salesLevel, 1);
assert.equal(departments.company.offerLevel, 1);
assert.equal(departments.inventory.companyItems, 0);
assert.equal(departments.coins, 3900, 'existing department coin costs remain in addition to items');

const legacy = api.newGame('hamburg');
legacy.version = 38;
legacy.company.transportUpgrades.national = { premiumBonus: .25, extraVolume: 20, extraRange: 40 };
legacy.orders[0].status = 'active';
legacy.orders[0].truckId = legacy.trucks[0].id;
legacy.orders[0].tripStartAt = Date.now();
legacy.orders[0].tripCargo = 4;
legacy.orders.push({ id: 'OLD-REWARD', category: 'national', kind: 'normal', status: 'completed', completionReward: { coins: 10, gears: {}, companyItems: 99, claimedAt: null } });
const oldTimer = legacy.nextAutoRefreshAt;
storage.set('frachtwerk-save-v2', JSON.stringify(legacy));
const migrated = api.loadGame();
assert.equal(migrated.version, 43);
assert.equal(migrated.company.transportUpgrades.national.premiumLevel, 25);
assert.equal(migrated.company.transportUpgrades.national.volumeLevel, 20);
assert.equal(migrated.company.transportUpgrades.national.rangeLevel, 40);
assert.equal(migrated.orders[0].status, 'active');
assert.equal(migrated.nextAutoRefreshAt, oldTimer + 10 * 60 * 1000);
assert.equal(api.loadGame().nextAutoRefreshAt, migrated.nextAutoRefreshAt, 'migration is one time');
assert.equal(migrated.inventory.companyItems, 0);
assert.equal(migrated.orders.find(item => item.id === 'OLD-REWARD').completionReward.companyItems, undefined, 'old rewards do not gain new item loot');
const previous = api.newGame('hamburg');
previous.version = 40;
delete previous.inventory.companyItemTkmRemainder;
previous.inventory.companyItems = 7;
previous.company.transportUpgrades.international.rangeLevel = 12;
previous.orders.push({ id: 'PENDING-OLD', category: 'national', kind: 'normal', status: 'completed', completionReward: { coins: 0, gears: {}, companyItems: 2, claimedAt: null } });
storage.set('frachtwerk-save-v2', JSON.stringify(previous));
const changed = api.loadGame();
assert.equal(changed.version, 43);
assert.equal(changed.inventory.companyItems, 7);
assert.equal(changed.inventory.companyItemTkmRemainder, 0, 'no retrospective ton-kilometer progress');
assert.equal(changed.company.transportUpgrades.international.rangeLevel, 12);
assert.equal(changed.orders.find(item => item.id === 'PENDING-OLD').completionReward.companyItems, 2, 'already determined old rewards remain');
assert.equal(api.loadGame().inventory.companyItemTkmRemainder, 0);

console.log('segment upgrades, persistent tkm items, crafting, material chance and migration: OK');
