const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const storage = new Map();
const math = Object.create(Math);
math.random = Math.random;
const dialog = { open: false, close() { this.open = false; } };
const context = vm.createContext({ localStorage: { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value) }, Date, Math: math, Intl, Number, JSON, setTimeout, clearTimeout, document: { querySelector: () => dialog } });
vm.runInContext(source.slice(0, source.indexOf("  document.addEventListener('click'")) + '\n globalThis.api = { START_CITIES, createOrder, newGame, loadGame, replenishOrders, manualRefreshOrders, autoRefreshOrders, assignOrder, upgradeOfferLimit, transportRules, setGame: value => { game = value; }, mute: () => { render = () => {}; showToast = () => {}; } };\n})();', context);
const api = context.api;
api.mute();
const available = state => state.orders.filter(order => order.status === 'available');
const chanceState = api.newGame('hamburg');
chanceState.expedition.regions[0].customerUnlocked = true;
api.setGame(chanceState);
math.random = () => .049;
assert.equal(api.createOrder(700, { category: 'national' }).customer, 'nordbau', 'unlocked customer can appear below 5 %');
math.random = () => .05;
assert.equal(api.createOrder(701, { category: 'national' }).customer, null, '5 % is excluded');
math.random = Math.random;
for (const home of api.START_CITIES) {
  const state = api.newGame(home.id);
  api.setGame(state);
  for (let i = 0; i < 100; i++) {
    const national = api.createOrder(1000 + i, { category: 'national', startCity: home.id });
    const international = api.createOrder(2000 + i, { category: 'international', startCity: home.id });
    assert.ok(national.distance >= 30 && national.distance <= 100, home.id);
    assert.ok(national.volume >= 10 && national.volume <= 40 && Number.isInteger(national.volume));
    assert.ok(international.volume >= 10 && international.volume <= 50 && Number.isInteger(international.volume));
    const routes = home.international.map(([, , km]) => km);
    const inRange = routes.filter(km => km >= 100 && km <= 200);
    const nearestGap = Math.min(...routes.map(km => Math.max(100 - km, 0, km - 200)));
    assert.ok(home.international.some(([, , km]) => km === international.distance), 'stored route distance is unchanged');
    if (inRange.length) assert.ok(international.distance >= 100 && international.distance <= 200, home.id);
    else assert.equal(Math.max(100 - international.distance, 0, international.distance - 200), nearestGap, 'closest stored route is used outside the target range');
  }
}
