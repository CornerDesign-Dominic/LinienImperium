const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const storage = new Map();
const math = Object.create(Math);
math.random = Math.random;
const dialog = { open: false, close() { this.open = false; } };
const context = vm.createContext({ localStorage: { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value) }, Date, Math: math, Intl, Number, JSON, setTimeout, clearTimeout, document: { querySelector: () => dialog } });
vm.runInContext(source.slice(0, source.indexOf("  document.addEventListener('click'")) + '\n globalThis.api = { START_CITIES, createOrder, newGame, loadGame, replenishOrders, manualRefreshOrders, autoRefreshOrders, assignOrder, upgradeOfferLimit, setGame: value => { game = value; }, mute: () => { render = () => {}; showToast = () => {}; } };\n})();', context);
const api = context.api;
api.mute();
const available = state => state.orders.filter(order => order.status === 'available');
for (const home of api.START_CITIES) {
  const state = api.newGame(home.id);
  api.setGame(state);
  for (let i = 0; i < 100; i++) {
    const national = api.createOrder(1000 + i, { category: 'national', startCity: home.id });
    const international = api.createOrder(2000 + i, { category: 'international', startCity: home.id });
    assert.ok(national.distance >= 40 && national.distance <= 180, home.id);
    assert.ok(national.volume >= 10 && national.volume <= 80);
    assert.ok(international.volume >= 10 && international.volume <= 60);
    assert.ok(home.international.some(([, , km]) => km === international.distance), 'stored route distance is unchanged');
    if (home.international.some(([, , km]) => km >= 150 && km <= 500)) assert.ok(international.distance >= 150 && international.distance <= 500, home.id);
  }
}
math.random = () => 0;
let state = api.newGame('hamburg');
assert.equal(available(state).length, 5);
assert.ok(available(state).every(order => order.category === 'international'));
math.random = () => .9;
state = api.newGame('hamburg');
assert.ok(available(state).every(order => order.category === 'national'));
api.setGame(state);
state.company.departments.dispatch = true;
state.coins = 50000;
api.upgradeOfferLimit();
assert.equal(state.company.offerLevel, 1);
assert.equal(available(state).length, 6);
state.company.departments.sales = true;
state.company.salesLevel = 1;
const pinned = available(state)[0];
pinned.pinned = true;
const timer = state.nextAutoRefreshAt;
api.manualRefreshOrders();
assert.ok(available(state).includes(pinned));
assert.equal(state.nextAutoRefreshAt, timer);
assert.equal(available(state).length, 6);
api.autoRefreshOrders(timer);
assert.ok(available(state).includes(pinned));
assert.equal(available(state).length, 6);
const assigned = available(state).find(order => order.category === 'national' && !order.pinned);
api.assignOrder(assigned.id, state.trucks[0].id);
assert.equal(assigned.status, 'active');
assert.equal(available(state).length, 6, 'assignment immediately refills the shared board');
const old = api.newGame('hamburg');
old.version = 35;
old.company.departments.dispatch = true;
old.company.offerLevels.national = 3;
old.company.offerLevels.international = 2;
old.orders[0].pinned = true;
storage.set('frachtwerk-save-v2', JSON.stringify(old));
const migrated = api.loadGame();
assert.equal(migrated.version, 37);
assert.equal(migrated.company.offerLevel, 5);
assert.equal(available(migrated).length, 5);
assert.ok(available(migrated).some(order => order.pinned));
api.setGame(migrated);
api.replenishOrders();
assert.equal(available(migrated).length, 10);
assert.equal(api.loadGame().company.offerLevel, 5, 'migration runs once');
const maxed = api.newGame('hamburg');
maxed.version = 35;
maxed.company.departments.dispatch = true;
maxed.company.offerLevels.national = 5;
maxed.company.offerLevels.international = 5;
storage.set('frachtwerk-save-v2', JSON.stringify(maxed));
const maxedMigrated = api.loadGame();
assert.equal(maxedMigrated.company.offerLevel, 10, 'all ten purchased legacy levels survive');
api.setGame(maxedMigrated);
api.replenishOrders();
assert.equal(available(maxedMigrated).length, 15);
console.log('shared offers, geography, pinning, refresh and purchased levels: OK');
